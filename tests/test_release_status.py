"""Software identity must distinguish loaded, installed, and published sources."""
from pathlib import Path
import tempfile
import unittest

from release_manifest import (BACKEND_FILES, FRONTEND_FILES, FRONTEND_ASSET_ROOTS,
                              HOSTED_FILES, HOSTED_ROOTS, NATIVE_FILES,
                              component_id, generate_manifest, source_files,
                              validate_manifest, write_embedded_manifest)
from release_status import ReleaseStatus, ReleaseUnavailable

ROOT = Path(__file__).resolve().parents[1]


class ReleaseFixture(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        for filename in set(FRONTEND_FILES + BACKEND_FILES + HOSTED_FILES + NATIVE_FILES):
            path = self.root / filename
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("source: " + filename + "\n", encoding="utf-8")
        for directory in FRONTEND_ASSET_ROOTS + HOSTED_ROOTS:
            (self.root / directory).mkdir(parents=True, exist_ok=True)
        self.manifest = generate_manifest(self.root)
        write_embedded_manifest(self.root / "static", self.manifest)

    def status(self, published=None, **options):
        tracker = ReleaseStatus(self.root, lambda: published or self.manifest, cache_seconds=0)
        return tracker, tracker.status(self.manifest["frontendId"], self.manifest["nativeId"], **options)


class ManifestTests(ReleaseFixture):
    def test_deterministic_and_excludes_credentials_user_data_and_generated_output(self):
        before = generate_manifest(self.root)
        for filename in ("library-sync.json", "work/personal.json", "web/public/drive-config.json",
                         "static/spiral/local-emblems/private.json", "hosting/worker/release-manifest.json",
                         ".git/config", "hosting/scripts/.env"):
            path = self.root / filename
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("private or generated bytes")
        self.assertEqual(before, generate_manifest(self.root))
        write_embedded_manifest(self.root / "static", before)
        self.assertEqual(before, generate_manifest(self.root))

    def test_each_component_detects_relevant_source_changes(self):
        for filename, component in (("static/app.js", "frontend"), ("library_sync.py", "backend"),
                                    ("hosting/worker/index.ts", "hosted"), ("desktop/ShardAtlas.swift", "native")):
            path = self.root / filename
            if not path.exists():
                path.write_text("old")
            before = generate_manifest(self.root)
            original = path.read_bytes()
            path.write_bytes(original + b"\nchanged")
            after = generate_manifest(self.root)
            self.assertNotEqual(before[component + "Id"], after[component + "Id"], filename)
            self.assertNotEqual(before["releaseId"], after["releaseId"], filename)
            path.write_bytes(original)

    def test_complete_manifest_validation_and_symlink_rejection(self):
        self.assertEqual(validate_manifest(self.manifest), self.manifest)
        for key in ("schemaVersion", "application", "nativeId"):
            damaged = dict(self.manifest)
            damaged[key] = "invalid"
            with self.assertRaises(ValueError):
                validate_manifest(damaged)
        path = self.root / "static/spiral/unsafe.svg"
        path.symlink_to(self.root / "server.py")
        with self.assertRaisesRegex(ValueError, "symlinks"):
            generate_manifest(self.root)

    def test_source_allowlists_cover_runtime_modules(self):
        allowed = set(FRONTEND_FILES + NATIVE_FILES)
        generated = {"release-manifest.js", "release-manifest.json", "build-info.json"}
        for path in (ROOT / "static").iterdir():
            if path.suffix in {".js", ".css", ".html", ".json"} and path.name not in generated:
                self.assertIn(path.relative_to(ROOT).as_posix(), allowed, "Add new runtime sources to the manifest allowlist")
        for path in (ROOT / "web").glob("*.mjs"):
            self.assertIn(path.relative_to(ROOT).as_posix(), FRONTEND_FILES)
        for path in (ROOT / "sync").glob("*.mjs"):
            self.assertIn(path.relative_to(ROOT).as_posix(), set(FRONTEND_FILES + HOSTED_FILES))
        for path in (ROOT / "desktop").iterdir():
            if path.suffix in {".swift", ".py", ".icns"}:
                self.assertIn(path.relative_to(ROOT).as_posix(), NATIVE_FILES)


class ReleaseStatusTests(ReleaseFixture):
    def test_matching_relevant_components_are_current_even_if_hosted_only_changed(self):
        published = dict(self.manifest, hostedId="a" * 64, releaseId="b" * 64)
        _, value = self.status(published)
        self.assertEqual(value["state"], "up_to_date")
        self.assertTrue(value["publishedAvailable"])
        self.assertIsNotNone(value["checkedAt"])
        self.assertTrue(all(c["matchesPublished"] for c in value["components"].values()))

    def test_backend_change_on_disk_requires_restart_even_without_network(self):
        tracker = ReleaseStatus(self.root, lambda: (_ for _ in ()).throw(OSError("offline")))
        (self.root / "library_sync.py").write_text("different installed runtime")
        value = tracker.status(self.manifest["frontendId"], self.manifest["nativeId"])
        self.assertEqual(value["state"], "restart_required")
        self.assertFalse(value["publishedAvailable"])

    def test_missing_or_different_compiled_stamp_requires_native_rebuild(self):
        tracker, _ = self.status()
        for stamp in (None, "", "a" * 64):
            self.assertEqual(tracker.status(self.manifest["frontendId"], stamp)["state"], "native_update_required")
        _, value = self.status(dict(self.manifest, nativeId="b" * 64))
        self.assertEqual(value["state"], "native_update_required")

    def test_loaded_frontend_and_published_differences_remain_distinct(self):
        tracker, _ = self.status()
        self.assertEqual(tracker.status("a" * 64, self.manifest["nativeId"])["state"], "update_available")
        for key in ("frontendId", "backendId"):
            _, value = self.status(dict(self.manifest, **{key: "a" * 64}))
            self.assertEqual(value["state"], "versions_differ")
        self.assertEqual(tracker.status(None, self.manifest["nativeId"])["state"], "unknown")

    def test_failed_check_never_reports_current_or_keeps_last_success_as_current(self):
        calls = []
        def fetch():
            calls.append(True)
            if len(calls) > 1:
                raise OSError("network failed")
            return self.manifest
        tracker = ReleaseStatus(self.root, fetch, cache_seconds=0)
        self.assertEqual(tracker.status(self.manifest["frontendId"], self.manifest["nativeId"])["state"], "up_to_date")
        failed = tracker.status(self.manifest["frontendId"], self.manifest["nativeId"])
        self.assertEqual(failed["state"], "offline")
        self.assertIsNone(failed["published"])
        self.assertIsNone(failed["checkedAt"])
        self.assertFalse(failed["publishedAvailable"])

    def test_invalid_published_reference_unpaired_and_cached_success(self):
        tracker = ReleaseStatus(self.root, lambda: {"bad": "manifest"}, cache_seconds=0)
        self.assertEqual(tracker.status(self.manifest["frontendId"], self.manifest["nativeId"])["state"], "unknown")
        tracker = ReleaseStatus(self.root)
        self.assertEqual(tracker.status(self.manifest["frontendId"], self.manifest["nativeId"])["state"], "unknown")
        with self.assertRaises(ReleaseUnavailable):
            tracker.published_manifest()
        calls = []
        def fetch():
            calls.append(True)
            return self.manifest
        tracker = ReleaseStatus(self.root, fetch)
        tracker.published_manifest()
        tracker.published_manifest()
        self.assertEqual(len(calls), 1)


